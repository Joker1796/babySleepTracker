// Что делать при ночном пробуждении — зависит от возраста, времени
// и от того, сколько прошло после отбоя.
// До 4 месяцев ночные кормления — по требованию, без интервалов.
// Правило про интервал между кормлениями — только с ~6 месяцев и с оговоркой.
const NIGHT_CALM = 'Ночью лучше не включать яркий свет, не разговаривать в полный голос и не устраивать игр — пусть всё говорит малышу, что сейчас ночь.'

const HUNGRY_FEED = 'Если малыш голоден (ищет грудь, чмокает, тянет ручки ко рту) — кормите по требованию, без оглядки на часы.'

export function nightAlgorithm({ hour, hoursSinceBedtime, ageM = null }) {
  const young = ageM != null && ageM < 4
  const canStretch = ageM != null && ageM >= 6

  if (hour >= 5 && hour < 7) {
    return {
      title: 'Раннее утро (5–7)',
      lines: [
        'Покормите, если малыш голоден, — тихо и в полумраке, лучше не выходя из спальни.',
        'Если проснулся от шума и уснул сам — не вмешивайтесь.',
        NIGHT_CALM
      ]
    }
  }

  // Малыши до 4 месяцев: ночные кормления нужны, никаких интервалов.
  if (young) {
    return {
      title: 'Ночное кормление',
      lines: [
        'В этом возрасте проснуться от голода ночью — нормально. ' + HUNGRY_FEED,
        'Кормите в полумраке, спокойно, затем подержите столбиком и уложите на спину в кроватку.',
        'Если не голоден — проверьте подгузник на ощупь и покачайте, тихо пошипите «шшш».',
        NIGHT_CALM
      ]
    }
  }

  if (hoursSinceBedtime != null && hoursSinceBedtime >= 3) {
    return {
      title: 'Ночное кормление',
      lines: [
        'Прошло 3+ часа после отбоя — если малыш голоден, покормите в полумраке, без разговоров, и уложите обратно в кроватку на спину.',
        NIGHT_CALM
      ]
    }
  }

  const lines = [
    'Прошло меньше 3 часов после отбоя — сначала проверьте подгузник на ощупь, не включая свет. Если сухой — попробуйте успокоить в кроватке: рука на груди, тихое «шшш», покачивание.'
  ]
  if (canStretch) {
    lines.push('Если малыш хорошо прибавляет в весе и педиатр не против, можно постараться увеличить промежуток между ночными кормлениями: сначала успокоить, а покормить, если не помогает. Не уверены — кормите, голод важнее режима.')
  } else {
    lines.push(HUNGRY_FEED)
  }
  lines.push(NIGHT_CALM)
  return { title: 'Ночное пробуждение', lines }
}
