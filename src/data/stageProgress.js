// Ободряющий разбор «было → стало» по этапам. Показывается в утренней сводке,
// когда возраст малыша соответствует этапу.
export const STAGE_PROGRESS = [
  {
    fromM: 2, toM: 3,
    text: 'Вспомните, с какого хаоса всё начиналось: укладывание по настроению, сны по 20–30 минут только на руках, пробуждения каждый час-два и тревога при каждом писке. Многие малыши к этому времени уже бодрствуют около 75–90 минут между снами, некоторые сны удлиняются и иногда удаются в кроватке, а ночью пробуждений становится меньше. Если у вас пока иначе — это тоже нормально: каждый малыш идёт своим темпом. А вы уже знаете своего ребёнка гораздо лучше, умеете замечать его сигналы и опираться на план.'
  }
]

export function stageProgressFor(ageMonths) {
  const s = STAGE_PROGRESS.find(x => ageMonths >= x.fromM && ageMonths < x.toM)
  return s ? s.text : null
}
