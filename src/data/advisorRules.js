// «3 дневных сна» / «2–3 дневных сна» — по диапазону норм
export function napsNormLabel(naps) {
  const [a, b] = naps
  if (a === b) return `${a} ${plural(a, 'дневной сон', 'дневных сна', 'дневных снов')}`
  return `${a}–${b} ${plural(b, 'дневной сон', 'дневных сна', 'дневных снов')}`
}

